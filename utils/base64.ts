// Tiny base64 helpers, kept apart from blindRsa.client so light callers don't pull in the RSA library.

// Convert Uint8Array to base64 string (browser-compatible)
export function toBase64(data: Uint8Array): string {
  let binary = ''
  for (let i = 0; i < data.length; i++) {
    binary += String.fromCharCode(data[i])
  }
  return btoa(binary)
}

// Convert base64 string to Uint8Array (browser-compatible)
export function fromBase64(base64: string): Uint8Array {
  const binary = atob(base64)
  const bytes = new Uint8Array(binary.length)
  for (let i = 0; i < binary.length; i++) {
    bytes[i] = binary.charCodeAt(i)
  }
  return bytes
}
